import { neon } from "@neondatabase/serverless";
import type { NeonQueryFunction } from "@neondatabase/serverless";
import type { Env } from "./types";

export type WorkerSql = NeonQueryFunction<false, false>;

export function createSql(env: Env): WorkerSql {
  if (!env.DATABASE_URL?.trim()) {
    throw new Error("DATABASE_URL Worker secret is not configured.");
  }
  return neon(env.DATABASE_URL.trim());
}

// Cloudflare Workers do not run SQL migration files automatically. Initialize the
// PostgreSQL schema on the first database access in each isolate. The statements
// are idempotent and safe when multiple requests arrive at the same time.
type SchemaState = { databaseUrl: string; promise: Promise<void> };
let schemaState: SchemaState | null = null;

async function initializeAnalysisSchema(sql: WorkerSql): Promise<void> {
  await sql`
    CREATE TABLE IF NOT EXISTS analysis_records (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      symbol VARCHAR(16) NOT NULL DEFAULT 'XAUUSD',
      tf_primary VARCHAR(8) NOT NULL DEFAULT 'M1',
      tf_secondary VARCHAR(8) NOT NULL DEFAULT 'M5',
      direction VARCHAR(8) NOT NULL DEFAULT 'WAIT',
      confidence DOUBLE PRECISION NOT NULL DEFAULT 0,
      entry_low DOUBLE PRECISION,
      entry_high DOUBLE PRECISION,
      stop_loss DOUBLE PRECISION,
      take_profit_1 DOUBLE PRECISION,
      take_profit_2 DOUBLE PRECISION,
      image_primary VARCHAR(255) NOT NULL DEFAULT '',
      image_secondary VARCHAR(255) NOT NULL DEFAULT '',
      payload_json TEXT NOT NULL DEFAULT '{}'
    )
  `;
  await sql`CREATE INDEX IF NOT EXISTS idx_analysis_records_created_at ON analysis_records (created_at DESC)`;
  await sql`CREATE INDEX IF NOT EXISTS idx_analysis_records_symbol_direction ON analysis_records (symbol, direction)`;
}

export async function getSql(env: Env): Promise<WorkerSql> {
  const sql = createSql(env);
  const databaseUrl = env.DATABASE_URL.trim();

  if (!schemaState || schemaState.databaseUrl !== databaseUrl) {
    const state: SchemaState = { databaseUrl, promise: Promise.resolve() };
    state.promise = initializeAnalysisSchema(sql).catch((error) => {
      // Permit a later request to retry after a temporary connection/permission failure.
      if (schemaState === state) schemaState = null;
      throw error;
    });
    schemaState = state;
  }

  await schemaState.promise;
  return sql;
}

export async function firstRow<T>(rows: Promise<T[]>): Promise<T | null> {
  const result = await rows;
  return result[0] ?? null;
}

export function logDatabaseError(event: string, error: unknown): void {
  const code = error && typeof error === "object" && "code" in error
    ? String((error as { code?: unknown }).code || "")
    : "";
  const name = error instanceof Error ? error.name : "UnknownError";
  const rawMessage = error instanceof Error ? error.message : String(error);
  const message = rawMessage.replace(/postgres(?:ql)?:\/\/\S+/gi, "[database-url-redacted]").slice(0, 300);
  console.error(JSON.stringify({ event, error_name: name, ...(code ? { postgres_code: code } : {}), error_message: message }));
}
